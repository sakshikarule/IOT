string = "Sunbeam Infotech"

print(f"string = {string[0]}")
print(f"string = {string[1]}")
print(f"string = {string[2]}")

print(f"string = {string[-1]}")
print(f"string = {string[-2]}")
print(f"string = {string[-3]}")


# first index is 0
# positive index - counting will start in forward direction
# negative index - counting will start in reverse direction

print(f"string[3:7] = {string[3:7]}")       # beam
    # string[m:n] - characters from m to n-1 index

print(f"string[:7] = {string[:7]}")       # beam
    # string[:n] - characters from first to n-1 index

print(f"string[3:] = {string[3:]}")       # beam
    # string[m:] - characters from m to last index
